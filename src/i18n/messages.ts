export type MessageKey = Key;
const dict: Record<Lang, Record<Key, string>> = { pt, en };

export function t(lang: Lang, key: MessageKey, params: Params = {}): string {
  const text = dict[lang][key] ?? dict.pt[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

/** 'pt-BR', 'pt_BR.UTF-8', 'pt' → 'pt'; qualquer outra coisa → 'en'. */
export const langFrom = (locale: string | undefined | null): Lang => (/^pt\b|^pt[-_]/i.test(String(locale ?? '')) ? 'pt' : 'en');

export function hasKey(key: string): key is MessageKey {
  return key in pt;
}
